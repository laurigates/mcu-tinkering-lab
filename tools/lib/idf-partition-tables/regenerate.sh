#!/usr/bin/env bash
# Regenerate the resolved copies of ESP-IDF's built-in partition tables.
#
# ESP-IDF's presets (CONFIG_PARTITION_TABLE_SINGLE_APP, _TWO_OTA, ...) live in
# the IDF tree as CSVs with every offset blank; gen_esp32part.py places them at
# build time. tools/lib/otadata-predicate.sh needs real offsets on a host with
# no ESP-IDF (CI's release job, pre-commit), so this script runs ESP-IDF's own
# gen_esp32part.py in the pinned image, CSV -> binary -> CSV, and writes each
# result here with every offset filled in (issue #684).
#
# The offsets assume the partition table at its default 0x8000; the predicate
# refuses to use these copies when CONFIG_PARTITION_TABLE_OFFSET moves it.
#
# Run after changing IDF_VERSION (the ESP-IDF upgrade): the tripwire in
# tools/test_check_flash_recipes.py fails until IDF_VERSION matches the version
# the builds use, and this script is what makes the copies match it.
#
# Usage: tools/lib/idf-partition-tables/regenerate.sh
# Env:   CONTAINER_CMD  docker (default) or podman

set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
version="$(tr -d '[:space:]' < "${here}/IDF_VERSION")"
image="espressif/idf:${version}"

# shellcheck disable=SC2016  # $IDF_PATH and friends expand inside the container
"${CONTAINER_CMD:-docker}" run --rm -v "${here}:/out" -e IDF_VER_LABEL="$version" "$image" bash -c '
    set -euo pipefail
    cd "$IDF_PATH/components/partition_table"
    rm -f /out/partitions_*.csv
    for src in partitions_*.csv; do
        python gen_esp32part.py -q "$src" /tmp/table.bin
        # Not /dev/stdout: the script reopens its output path, which would
        # truncate the redirected file and drop the header above it.
        python gen_esp32part.py -q /tmp/table.bin /tmp/table.csv
        {
            echo "# ESP-IDF ${IDF_VER_LABEL} components/partition_table/${src}, with every offset"
            echo "# placed by gen_esp32part.py behind a partition table at 0x8000."
            echo "# Generated by tools/lib/idf-partition-tables/regenerate.sh; do not edit."
            cat /tmp/table.csv
        } > "/out/${src}"
    done
' 2>&1 | grep -v -E '^(Checking|Python|"python3"|Activating|\*|Done!|Go to|  idf\.py|$)' || true

count=$(find "$here" -name 'partitions_*.csv' | wc -l | tr -d ' ')
if [[ "$count" -eq 0 ]]; then
    echo "ERROR: no tables written to ${here}" >&2
    exit 1
fi
echo "Wrote ${count} tables from ${image} to ${here}"
