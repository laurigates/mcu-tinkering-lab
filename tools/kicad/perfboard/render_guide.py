"""The step guide: a printable Typst document, one landscape A4 page per build step.

Page 1 is the component side and the parts. Each step page puts that step's
solder-side panel, cropped from perfboard.svg, beside its wire list and the
continuity checks to run once it is soldered; the last page is the rails that
must not beep. It holds no drawing of its own: the panels are clips of the
committed perfboard.svg (`render_svg.body`, one `<g id="panel-N">` each), and the rows are the wire list's
and checklist's (`wirelist.step_rows`, `continuity.beep_rows`), so the printed
pages and the Markdown cannot disagree.

It is written to the project's `docs/`, where `just <project>::build-guide`
compiles it and build-guide-check.yml holds the committed PDF to it.
"""

from __future__ import annotations

import os

from . import continuity, render_svg, wirelist
from .config import PerfboardConfig
from .grid import hole_name

FILENAME = "perfboard-steps.typ"
# The panel's box on the page, mm: the left column of a landscape A4 page
# with 10 mm margins, below the page heading.
PANEL_W, PANEL_H = 130, 172

PREAMBLE = """\
// Generated by tools/kicad (python3 -m kicad.perfboard) from hardware.toml; do not edit.
#set page("a4", flipped: true, margin: (x: 12mm, y: 10mm),
  footer: context align(right, text(8pt, luma(120))[#{title} · #counter(page).display()]))
#set text(font: "Libertinus Serif", size: 10pt)
#show heading.where(level: 1): set text(14pt)
#show heading.where(level: 2): set text(11pt)
#let check = box(width: 7pt, height: 7pt, stroke: 0.6pt)
#let rows(columns, header, ..cells) = text(7.5pt, table(
  columns: columns, inset: (x: 3pt, y: 2.2pt), stroke: 0.4pt + luma(170), align: left,
  table.header(..header.map(h => strong(h))), ..cells))
// Panel i is perfboard.svg's root tag with its viewBox narrowed to the panel,
// around that panel's group alone, so a page embeds one panel, not six. (A clip
// box around the whole image lands the crop several rows off in Typst 0.15.)
#let drawing = read("{svg}")
#let root = drawing.split(">").first() + ">"
#let panel(i, x, y, w, h) = {{
  let group = "<g id=\\"panel-" + str(i) + "\\">"
  let body = drawing.split(group).at(1).split("</g>").first()
  let tag = root.replace(
    "width=\\"{width}\\" height=\\"{height}\\"",
    "viewBox=\\"" + str(x) + " " + str(y) + " " + str(w) + " " + str(h) + "\\" width=\\"" + str(w) + "\\" height=\\"" + str(h) + "\\"")
  image(bytes(tag + group + body + "</g></svg>"), format: "svg", width: w * {k})
}}
"""


def s(text) -> str:
    """`text` as a Typst string literal."""
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def table(header, rows, checks=True):
    cells = [
        ", ".join((["check"] if checks else []) + [s(c) for c in row]) for row in rows
    ]
    head = (['""'] if checks else []) + [s(h) for h in header]
    widths = ["auto"] * (len(head) - 1) + ["1fr"]
    return (
        f"#rows(({', '.join(widths)},), ({', '.join(head)},),\n  "
        + ",\n  ".join(cells)
        + ")"
    )


def page(index, title, board, side):
    x, y, w, h = render_svg.body(index, board)
    return "\n".join(
        [
            f"#heading(level: 1, {s(title)})",
            "#grid(columns: (auto, 1fr), gutter: 12pt,",
            f"  panel({index}, {x}, {y}, {w}, {h}),",
            "  [",
            side,
            "  ])",
        ]
    )


def guide(
    parts, nets, numbered, routes, cfg: PerfboardConfig, heavy, guide_dir, svg_path
):
    board = cfg.board
    width, height = render_svg.size(board, cfg.steps)
    _, _, w, h = render_svg.body(0, board)
    k = min(PANEL_W / w, PANEL_H / h)
    pages = []
    parts_rows = [
        (p.ref, p.value, hole_name(*p.pads["1"]))
        for p in sorted(parts.values(), key=lambda p: p.ref)
    ]
    pages.append(
        page(
            0,
            "Component side",
            board,
            "\n".join(
                [
                    "#"
                    + s(
                        "Holes are named from the component side: the solder-side "
                        "panels are mirrored, the names are not. Each step page lists "
                        "its wires, numbered as drawn; tick each one off as you solder "
                        "it, then run that step's continuity checks. "
                        f"Heavy nets ({cfg.heavy_label}) need {cfg.heavy_gauge} or "
                        f"heavier and are drawn thicker; everything else {cfg.light_gauge}."
                    ),
                    "#v(6pt)",
                    "== Parts",
                    table(("Ref", "Part", "Pin 1 at"), parts_rows, checks=False),
                ]
            ),
        )
    )
    for step, st in enumerate(cfg.steps):
        rows = list(wirelist.step_rows(numbered, routes, cfg, heavy, step))
        title = f"Step {step + 1} · {st.title} (wires {rows[0][0]}–{rows[-1][0]})"
        side = "\n".join(
            [
                f"#text(9pt, {s(st.subtitle[0].upper() + st.subtitle[1:] + '.')})",
                table(("#", "Net", "Gauge", "From", "To", "Holes"), rows),
                "#v(6pt)",
                "== Continuity after this step",
                table(
                    ("Net", "Probe on", "Must beep to"),
                    continuity.beep_rows(parts, nets, st),
                ),
            ]
        )
        pages.append(page(step + 1, title, board, side))
    if cfg.isolated:
        pages.append(
            "\n".join(
                [
                    '#heading(level: 1, "Before first power-up")',
                    "#"
                    + s(
                        "Each pair must not beep. Then read it on the resistance range: "
                        "a reading that starts low and climbs is a capacitor charging, "
                        "kilohms is a resistor between the rails, and one that stays "
                        "near 0 Ω is a short. Fit the modules only when every pair passes."
                    ),
                    "#v(6pt)",
                    table(
                        ("Rail", "Rail", "Probe on", "And on"),
                        continuity.isolated_rows(parts, nets, cfg),
                    ),
                ]
            )
        )
    svg = os.path.relpath(svg_path, guide_dir).replace(os.sep, "/")
    preamble = PREAMBLE.format(
        title=s(cfg.title), k=f"{k:.4f}mm", svg=svg, width=width, height=height
    )
    return preamble + "\n" + "\n#pagebreak()\n".join(pages) + "\n"
